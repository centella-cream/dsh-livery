#!/usr/bin/env node
/**
 * DSH Livery build.
 *
 * Order matters:
 *  1. bundle the two Node CLIs (compiler + contract),
 *  2. compile liveries -> src/generated/liveries.ts + lib/previews/,
 *  3. bundle the Host plugin (ESM, node builtins external),
 *  4. bundle the Client plugin (CJS factory wrapped in the DSH loader envelope).
 *
 * The build must work in a clean checkout: generated contract/token files are
 * committed, and no step reads `references/`, `research/` or a local DSH path.
 */
import { execFileSync } from 'node:child_process'
import { gzipSync } from 'node:zlib'
import { existsSync } from 'node:fs'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))

const PLATFORM_MODULES = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

const nodeTarget = (pkg.engines?.node ?? '>=22').includes('24') ? 'node22' : 'node22'
const started = Date.now()

async function ensureDir(path) {
  await mkdir(path, { recursive: true })
}

async function buildNodeCli(entry, outfile) {
  await build({
    entryPoints: [join(root, entry)],
    outfile: join(root, outfile),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: nodeTarget,
    sourcemap: false,
    logLevel: 'warning',
    // These packages ship CJS internals that cannot be bundled into an ESM CLI.
    external: ['postcss', 'ajv'],
    banner: { js: `// dsh-livery — generated by scripts/build.mjs (${entry})` },
  })
  console.log(`build: ${outfile}`)
}

async function runCompiler(command) {
  const cli = join(root, 'lib', 'cli', 'compiler.js')
  if (!existsSync(cli)) {
    console.warn('build: compiler CLI missing — skipping liveries:compile (run after the compiler module lands)')
    return false
  }
  execFileSync(process.execPath, [cli, command], { cwd: root, stdio: 'inherit' })
  return true
}

async function buildHost() {
  const outfile = join(root, 'lib', 'index.js')
  await build({
    entryPoints: [join(root, 'src', 'host', 'index.ts')],
    outfile,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: nodeTarget,
    sourcemap: false,
    minify: true,
    logLevel: 'warning',
    external: ['@deepseek-ai/dsh-app-boot'],
    banner: {
      js: '// dsh-livery host plugin — ESM, built deterministically from a clean tree.',
    },
  })
  console.log('build: lib/index.js')
}

async function buildClient() {
  const outfile = join(root, 'lib', 'client.js')
  await build({
    entryPoints: [join(root, 'src', 'client', 'index.tsx')],
    outfile,
    bundle: true,
    platform: 'browser',
    format: 'cjs',
    target: 'chrome120',
    sourcemap: false,
    minify: true,
    logLevel: 'warning',
    jsx: 'automatic',
    external: PLATFORM_MODULES,
    define: { 'process.env.NODE_ENV': '"production"' },
    banner: {
      js: `window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;`,
    },
    footer: {
      js: `    return module.exports;
  }
});`,
    },
  })
  console.log('build: lib/client.js')
}

async function checkSizes() {
  // Performance budgets from docs/design/implementation-plan.md §18.8, per catalog profile.
  const CLIENT_GZIP_BUDGET = 56 * 1024
  const HOST_GZIP_BUDGET = 192 * 1024
  const PER_LIVERY_CSS_BUDGET = 12 * 1024
  const client = await readFile(join(root, 'lib', 'client.js'))
  const host = await readFile(join(root, 'lib', 'index.js'))
  const clientGzip = gzipSync(client, { level: 9 }).byteLength
  const hostGzip = gzipSync(host, { level: 9 }).byteLength

  // Compiler layout: artifacts/liveries/<profileId>/{report,contrast,token-coverage,css-safety}.json
  // plus artifacts/liveries/summary.json mapping adapters -> profile.
  let profileIds = []
  let maxLiveryCss = 0
  let liveryCount = 0
  let cssSafety = 'missing'
  try {
    const summary = JSON.parse(await readFile(join(root, 'artifacts', 'liveries', 'summary.json'), 'utf8'))
    profileIds = Array.isArray(summary.profiles) ? summary.profiles.map((profile) => profile.profileId ?? profile.id) : []
  } catch {
    // fall back to scanning profile dirs
  }
  if (profileIds.length === 0) {
    try {
      const { readdir } = await import('node:fs/promises')
      const entries = await readdir(join(root, 'artifacts', 'liveries'), { withFileTypes: true })
      profileIds = entries.filter((entry) => entry.isDirectory()).map((entry) => entry.name)
    } catch {
      profileIds = []
    }
  }
  let profileReports = 0
  for (const profileId of profileIds) {
    try {
      const report = JSON.parse(await readFile(join(root, 'artifacts', 'liveries', profileId, 'report.json'), 'utf8'))
      profileReports += 1
      const profileLiveries = report.counts?.liveries ?? report.liveries?.length ?? 0
      if (profileLiveries > 0) {
        liveryCount = liveryCount === 0 ? profileLiveries : Math.min(liveryCount, profileLiveries)
      }
      maxLiveryCss = Math.max(maxLiveryCss, report.counts?.maxLiveryCssBytes ?? 0)
      if (report.gates?.cssSafety === false) cssSafety = 'fail'
      else if (cssSafety === 'missing') cssSafety = 'pass'
    } catch {
      // missing profile report is caught by the profileReports check
    }
  }

  const problems = []
  try {
    const pkgForBuild = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
    const matrixForBuild = JSON.parse(await readFile(join(root, 'contracts', 'dsh', 'support-matrix.json'), 'utf8'))
    const expectedEngines = matrixForBuild.entries
      .filter((entry) => entry.status === 'g6-approved' || entry.status === 'released')
      .map((entry) => entry.hostVersion)
      .sort()
      .join(' || ')
    if (pkgForBuild.engines?.dsh !== expectedEngines) {
      problems.push(`package.json engines.dsh must be the exact shipped allowlist "${expectedEngines}", got "${String(pkgForBuild.engines?.dsh)}"`)
    }
  } catch (error) {
    problems.push(`cannot validate narrow engines allowlist: ${error.message}`)
  }
  if (clientGzip > CLIENT_GZIP_BUDGET) problems.push(`client gzip ${clientGzip}B exceeds ${CLIENT_GZIP_BUDGET}B budget`)
  if (hostGzip > HOST_GZIP_BUDGET) problems.push(`host gzip ${hostGzip}B exceeds ${HOST_GZIP_BUDGET}B budget`)
  if (maxLiveryCss > PER_LIVERY_CSS_BUDGET) problems.push(`largest livery css ${maxLiveryCss}B exceeds ${PER_LIVERY_CSS_BUDGET}B budget`)
  // The formal support matrix decides the shipped adapter set; historical
  // snapshots are not compiled. Today the narrowed release line has one adapter
  // and therefore one catalog profile, but the check stays count-driven.
  let shippedAdapters = 0
  try {
    const matrix = JSON.parse(await readFile(join(root, 'contracts', 'dsh', 'support-matrix.json'), 'utf8'))
    shippedAdapters = matrix.entries.filter(
      (entry) => entry.status === 'g6-approved' || entry.status === 'released',
    ).length
  } catch (error) {
    problems.push(`cannot read formal support matrix: ${error.message}`)
  }
  if (shippedAdapters === 0) problems.push('formal support matrix has no g6-approved/released adapter')
  if (profileReports < 1) problems.push(`expected at least 1 compiled catalog profile, found ${profileReports}`)
  if (profileIds.length > shippedAdapters) {
    problems.push(`compiled ${profileIds.length} catalog profiles for only ${shippedAdapters} shipped adapter(s)`)
  }
  if (liveryCount < 10) problems.push(`catalog profile has only ${liveryCount} liveries (expected the full design set)`)
  if (cssSafety === 'fail') problems.push('compiler CSS safety report failed')
  // Every profile must ship the same design set, and its preview index must hold
  // exactly liveries x 4 files (zh/en x light/dark).
  const profileCounts = new Map()
  for (const profileId of profileIds) {
    try {
      const report = JSON.parse(await readFile(join(root, 'artifacts', 'liveries', profileId, 'report.json'), 'utf8'))
      profileCounts.set(profileId, report.counts?.liveries ?? 0)
    } catch {}
    try {
      const index = JSON.parse(await readFile(join(root, 'lib', 'previews', profileId, 'index.json'), 'utf8'))
      const count = (index.files ?? []).length
      const expected = (profileCounts.get(profileId) ?? 0) * 4
      if (expected > 0 && count !== expected) problems.push(`previews/${profileId} must contain ${expected} svg files (liveries x 4), found ${count}`)
    } catch {
      problems.push(`previews/${profileId}/index.json is missing`)
    }
  }
  const distinctCounts = new Set([...profileCounts.values()].filter((n) => n > 0))
  if (distinctCounts.size > 1) problems.push(`catalog profiles disagree on livery count: ${JSON.stringify(Object.fromEntries(profileCounts))}`)

  const report = {
    generatedAt: 'deterministic-build',
    nodeVersion: process.version,
    clientBytes: client.byteLength,
    clientGzip,
    hostBytes: host.byteLength,
    hostGzip,
    budgets: { clientGzip: CLIENT_GZIP_BUDGET, hostGzip: HOST_GZIP_BUDGET, bootCss: 12 * 1024, perLiveryCss: PER_LIVERY_CSS_BUDGET },
    profiles: profileIds,
    liveryCount,
    maxLiveryCss,
    cssSafety,
    pass: problems.length === 0,
    problems,
  }
  await writeFile(join(root, 'lib', 'build-report.json'), `${JSON.stringify(report, null, 2)}\n`)
  console.log(
    `build: host ${host.byteLength}B (gzip ${hostGzip}B) · client ${client.byteLength}B (gzip ${clientGzip}B) · profiles ${profileIds.join(', ')} · max livery css ${maxLiveryCss}B`,
  )
  if (problems.length > 0) {
    for (const problem of problems) console.error(`build: BUDGET FAIL ${problem}`)
    throw new Error('build budget gate failed')
  }
}

async function main() {
  if (!existsSync(join(root, 'node_modules', 'esbuild'))) {
    throw new Error('node_modules is missing; run `pnpm install` first')
  }
  const cliOnly = process.argv.includes('--cli-only')
  await ensureDir(join(root, 'lib'))
  await ensureDir(join(root, 'lib', 'cli'))
  if (!cliOnly) {
    await ensureDir(join(root, 'lib', 'previews'))
    // Remove stale artifacts from previous builds so drift is visible.
    await rm(join(root, 'lib', 'cli'), { recursive: true, force: true })
    await ensureDir(join(root, 'lib', 'cli'))
  }

  await buildNodeCli('src/compiler/cli.ts', 'lib/cli/compiler.js')
  await buildNodeCli('src/contract/cli.ts', 'lib/cli/contract.js')
  if (cliOnly) {
    console.log(`build:cli done in ${Date.now() - started}ms`)
    return
  }
  const compiled = await runCompiler('compile')
  if (compiled) {
    await buildHost()
    await buildClient()
    await checkSizes()
  } else {
    console.warn('build: host/client bundles were NOT rebuilt (compiler CLI is missing)')
  }
  console.log(`build: done in ${Date.now() - started}ms`)
}

await main()
